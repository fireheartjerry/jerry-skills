"""`dev.py init`: install dev.py into a repository as a shim plus configuration.

Writes `<repo>/tools/dev.py` (a shim of under 60 lines, marker `# devkit-shim v1`, that finds
the bundled dev.py and runs it in-process with DEVKIT_REPO set to the repository),
`<repo>/tools/dev.json` with detected values when absent, and `<repo>/.devkit/.gitignore`
holding `*`. A tools/dev.py without the marker is never overwritten unless --force.
"""
import json
import os
import subprocess
import sys

from devkit import VERSION
from devkit.common import (CONFIG_PATH, CONFIG_SCHEMA, DEFAULT_CONFIG, DEVKIT_DIR, DevError,
                           Parser, UsageError, load_config, note, print_json, repo_root,
                           to_posix)

SCHEMA = "devkit-init/1"
MARKER = "# devkit-shim v1"
MARKER_PREFIX = "# devkit-shim v"
DEFAULT_SHIM = "tools/dev.py"
SHIM_MAX_LINES = 60

SHIM = '''#!/usr/bin/env python3
# devkit-shim v1
"""Runs the competitive-systems skill's dev.py on this repository: python3 @SHIM@ help

Generated by `dev.py init`; commit it with tools/dev.json. Looks for the bundled dev.py in
$DEVKIT_DEV_PY, the path recorded at init, $CLAUDE_PLUGIN_ROOT, the project skill copies,
the home copies, then the newest Claude Code plugin install.
"""
import glob
import os
import runpy
import sys

RECORDED = @RECORDED@
UP = @UP@
REL = ("competitive-systems", "scripts", "dev.py")


def locations(repo):
    out = [("DEVKIT_DEV_PY", os.environ["DEVKIT_DEV_PY"])] if os.environ.get("DEVKIT_DEV_PY") else []
    if RECORDED:
        out.append(("recorded by init", os.path.join(repo, os.path.expanduser(RECORDED))))
    if os.environ.get("CLAUDE_PLUGIN_ROOT"):
        out.append(("plugin root", os.path.join(os.environ["CLAUDE_PLUGIN_ROOT"], "skills", *REL)))
    for d in (".claude", ".codex"):
        out.append(("project copy", os.path.join(repo, d, "skills", *REL)))
    home = os.path.expanduser("~")
    for d in (".claude", ".codex", ".agents"):
        out.append(("home copy", os.path.join(home, d, "skills", *REL)))
    cache = os.path.join(home, ".claude", "plugins", "cache", "*", "*", "*", "skills", *REL)
    found = sorted(glob.glob(cache), key=lambda p: (os.path.getmtime(p), p), reverse=True)
    out.append(("plugin install", found[0] if found else cache))
    return out


def main():
    repo = os.path.abspath(__file__)
    for _ in range(UP + 1):
        repo = os.path.dirname(repo)
    tried = []
    for label, path in locations(repo):
        if os.path.isfile(path):
            path = os.path.abspath(path)
            os.environ["DEVKIT_REPO"] = repo
            sys.path.insert(0, os.path.dirname(path))
            sys.argv = [path] + sys.argv[1:]
            runpy.run_path(path, run_name="__main__")
            return
        tried.append("  %-17s %s" % (label + ":", path))
    sys.stderr.write("@SHIM@: cannot find the competitive-systems dev.py; tried:\\n%s\\n"
                     "fix: export DEVKIT_DEV_PY=<skill-dir>/scripts/dev.py\\n"
                     "  or: python3 <skill-dir>/scripts/dev.py init  (records the path here)\\n"
                     % "\\n".join(tried))
    sys.exit(3)


if __name__ == "__main__":
    main()
'''

DOCS = {
    "_doc": "dev.py settings for this repository (competitive-systems skill). Every key is "
            "optional; references/tooling.md in the skill documents each one.",
    "_doc_languages": "restricts detection to these languages; null detects on every run",
    "_doc_commands": "null resolves the tool at run time; a string runs through the shell, "
                     "with {files}, {targets} and {report} replaced",
    "_doc_sensitive": "a change to a matching path runs the full test suite",
    "_doc_ignore": "a change to a matching path affects no test (the shim is listed here)",
    "_doc_test_map": "{source path or glob: [test targets]} replaces the import-graph result",
    "_doc_benchmarks": "[{\"name\": ..., \"command\": ..., \"runs\": 7}] for perf run",
}


def bundled_dev_py():
    return os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "dev.py")


def recorded_path(repo, bundled):
    """The bundled path as the shim records it: repository-relative when inside the
    repository, `~/...` under the home directory, else absolute. A Claude Code plugin
    install is not recorded: its path holds a version directory that the next plugin update
    removes, and the shim finds the newest install itself."""
    bundled = os.path.abspath(bundled)
    if os.sep + os.path.join(".claude", "plugins", "cache") + os.sep in bundled:
        return None
    rel = os.path.relpath(bundled, repo)
    if not (rel == os.pardir or rel.startswith(os.pardir + os.sep)):
        return to_posix(rel)
    home = os.path.expanduser("~")
    if home and home != os.sep and bundled.startswith(home.rstrip(os.sep) + os.sep):
        return "~/" + to_posix(os.path.relpath(bundled, home))
    return to_posix(bundled)


def shim_text(shim_rel, recorded):
    up = len([p for p in shim_rel.split("/")[:-1] if p])
    text = SHIM.replace("@SHIM@", shim_rel).replace("@RECORDED@", repr(recorded)) \
        .replace("@UP@", str(up))
    assert len(text.splitlines()) <= SHIM_MAX_LINES
    return text


def config_text(info, shim_rel=DEFAULT_SHIM):
    langs = list(info["languages"])
    globs = DEFAULT_CONFIG["test_globs"]
    cfg = {
        "_doc": DOCS["_doc"],
        "schema": CONFIG_SCHEMA,
        "languages": langs or None,
        "_doc_languages": DOCS["_doc_languages"],
        "package_manager": info.get("package_manager"),
        "commands": dict((l, {"lint": None, "typecheck": None, "test": None, "test_report": None})
                         for l in langs),
        "_doc_commands": DOCS["_doc_commands"],
        "sensitive": DEFAULT_CONFIG["sensitive"],
        "_doc_sensitive": DOCS["_doc_sensitive"],
        "ignore": DEFAULT_CONFIG["ignore"] + [shim_rel],
        "_doc_ignore": DOCS["_doc_ignore"],
        "exclude_dirs": DEFAULT_CONFIG["exclude_dirs"],
        "test_globs": dict((l, globs[l]) for l in langs if l in globs),
        "test_map": {},
        "_doc_test_map": DOCS["_doc_test_map"],
        "always_run": [],
        "benchmarks": [],
        "_doc_benchmarks": DOCS["_doc_benchmarks"],
        "size_audit": dict(DEFAULT_CONFIG["size_audit"]),
        "budget_seconds": DEFAULT_CONFIG["budget_seconds"],
        "max_changed_files": DEFAULT_CONFIG["max_changed_files"],
    }
    return json.dumps(cfg, indent=2) + "\n"


def marker_of(text):
    for line in text.splitlines()[:5]:
        if line.startswith(MARKER_PREFIX):
            return line.strip()
    return None


def _read(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            return f.read()
    except OSError:
        return None


def check(root, shim_rel, as_json):
    path = os.path.join(root, shim_rel)
    text = _read(path)
    status, detail = "ok", ""
    if text is None:
        status, detail = "missing", "%s does not exist; run `dev.py init`" % shim_rel
    elif marker_of(text) is None:
        status, detail = "foreign", "%s is not a devkit shim (no `%s` line)" % (shim_rel, MARKER)
    elif marker_of(text) != MARKER:
        status, detail = "outdated", "%s has %r, this dev.py writes %r; re-run `dev.py init`" % (
            shim_rel, marker_of(text), MARKER)
    else:
        p = subprocess.run([sys.executable, path, "--version"], stdout=subprocess.PIPE,
                           stderr=subprocess.PIPE, universal_newlines=True)
        if p.returncode != 0:
            status = "unresolved"
            detail = "%s exits %d: %s" % (shim_rel, p.returncode,
                                          " | ".join(p.stderr.strip().splitlines()[:8]))
        else:
            detail = "%s resolves (dev.py %s)" % (shim_rel, p.stdout.strip())
            if p.stdout.strip() != VERSION:
                detail += "; this copy is %s" % VERSION
    if as_json:
        print_json({"schema": SCHEMA, "mode": "check", "shim": shim_rel, "status": status,
                    "detail": detail})
    else:
        print("dev.py init: %s" % detail)
    return 0 if status == "ok" else 1


def cmd_init(args):
    p = Parser(prog="dev.py init", description="Install dev.py into a repository: the "
               "tools/dev.py shim, tools/dev.json (when absent) and .devkit/.gitignore.")
    p.add_argument("--repo", default=None, help="repository root (default: git top level)")
    p.add_argument("--force", action="store_true",
                   help="replace a tools/dev.py that is not a devkit shim")
    p.add_argument("--check", action="store_true",
                   help="exit 0 when the shim has the current marker and resolves, else 1")
    p.add_argument("--dry-run", action="store_true", help="print what would be written")
    p.add_argument("--shim-path", default=DEFAULT_SHIM,
                   help="where to write the shim, relative to the root (default %s)" % DEFAULT_SHIM)
    p.add_argument("--json", action="store_true", help="print one JSON object")
    a = p.parse_args(args)
    root, root_note = repo_root(a.repo)
    if root_note:
        note(root_note)
    shim_rel = to_posix(os.path.normpath(a.shim_path))
    if os.path.isabs(a.shim_path) or shim_rel.startswith("../") or shim_rel == ".." \
            or not shim_rel.endswith(".py"):
        raise UsageError("--shim-path must be a relative path inside the repository ending in .py")
    if a.check:
        return check(root, shim_rel, a.json)
    shim_abs = os.path.join(root, shim_rel)
    existing = _read(shim_abs)
    if existing is not None and marker_of(existing) is None and not a.force:
        raise DevError("a different %s exists; pass --force to replace it or --shim-path to "
                       "choose another name" % shim_rel)
    from devkit.detect import detect
    info = detect(root, load_config(root, warn_unknown=False))
    bundled = bundled_dev_py()
    recorded = recorded_path(root, bundled)
    plan = []
    action = "write" if existing is None else ("rewrite" if marker_of(existing) else "replace")
    plan.append((shim_rel, shim_text(shim_rel, recorded), action))
    cfg_abs = os.path.join(root, CONFIG_PATH)
    plan.append((CONFIG_PATH, config_text(info, shim_rel), "keep" if os.path.exists(cfg_abs) else "write"))
    ign_rel = DEVKIT_DIR + "/.gitignore"
    plan.append((ign_rel, "*\n", "keep" if os.path.exists(os.path.join(root, ign_rel)) else "write"))
    if not a.dry_run:
        for rel, text, act in plan:
            if act == "keep":
                continue
            full = os.path.join(root, rel)
            if not os.path.isdir(os.path.dirname(full)):
                os.makedirs(os.path.dirname(full))
            with open(full, "w", encoding="utf-8") as f:
                f.write(text)
            if rel == shim_rel:
                os.chmod(full, 0o755)
    if a.json:
        print_json({"schema": SCHEMA, "mode": "dry-run" if a.dry_run else "write",
                    "root": to_posix(root), "recorded": recorded,
                    "languages": info["languages"],
                    "actions": [{"path": rel, "action": act} for rel, _, act in plan]})
        return 0
    verb = {"write": "wrote", "rewrite": "rewrote", "replace": "replaced", "keep": "kept"}
    for rel, text, act in plan:
        if a.dry_run:
            if act == "keep":
                print("init: would keep %s (exists)" % rel)
                continue
            print("init: would %s %s (%d lines):" % (act, rel, len(text.splitlines())))
            for line in text.splitlines():
                print("    " + line)
            continue
        extra = ""
        if rel == shim_rel:
            extra = (" (shim; records %s)" % recorded) if recorded else \
                " (shim; finds the newest plugin install at run time)"
        elif rel == CONFIG_PATH:
            extra = " (exists)" if act == "keep" else " (languages: %s)" % (
                ", ".join(info["languages"]) or "none detected")
        print("init: %s %s%s" % (verb[act], rel, extra))
    if not a.dry_run:
        print("next: python3 %s detect; commit %s and %s (.devkit/ ignores itself)"
              % (shim_rel, shim_rel, CONFIG_PATH))
    return 0
